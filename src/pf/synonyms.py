"""Словарь лексической близости: группы взаимозаменяемых терминов.

Проверка оснований сравнивала слова буквально, поэтому «абоненты» в
источнике и «клиенты» в утверждении считались разными словами, и верное
утверждение отклонялось. Здесь собраны группы, внутри которых слова
означают одно и то же понятие.

Правила, без которых словарь приносит вред:

1. **Группа — это одно понятие, а не «похожие слова».** «Удержание» и
   «отток» стоят рядом в текстах, но означают разное; попади они в одну
   группу, проверка начнёт подтверждать противоположные утверждения.
2. **Словарь маленький и проверяемый.** Он правится человеком и
   покрывается тестом на противоречия (`tests/test_synonyms.py`).
3. **Первое слово группы — каноническая лемма.** К ней приводятся
   остальные: это делает сравнение независимым от формы записи.

Начальное наполнение лежит в данных (`knowledge/lexicon/synonyms.yaml`),
здесь — встроенный запасной вариант: агент работает и без файла. Файл
сильнее встроенного набора, потому что его можно расширять по мере
распознания незнакомых слов.
"""

from __future__ import annotations

from collections.abc import Mapping

#: Группы синонимов. Первое слово — каноническая лемма.
BUILTIN_GROUPS: tuple[tuple[str, ...], ...] = (
    # Аудитория: в открытых источниках эти слова взаимозаменяемы.
    ("абонент", "клиент", "пользователь", "subscriber", "customer"),
    # Показатели удержания. «Отток» намеренно НЕ здесь.
    ("удержание", "retention"),
    ("отток", "churn"),
    ("выручка", "revenue"),
    ("доход", "income"),
    # Участники рынка и продукт.
    ("оператор", "operator", "carrier"),
    ("тариф", "tariff"),
    ("подписка", "subscription"),
    ("услуга", "service"),
    # Названия из демонстрационной задачи: латиница и кириллица.
    ("мегафон", "megafon"),
    ("мтс", "mts"),
)

#: Пары, которые нельзя объединять ни при каких условиях. Нужны тесту:
#: если кто-то добавит «отток» в группу «удержание», тест покраснеет.
OPPOSITE_PAIRS: tuple[tuple[str, str], ...] = (
    ("удержание", "отток"),
    ("рост", "падение"),
    ("выручка", "убыток"),
)


def build_map(groups: tuple[tuple[str, ...], ...] = BUILTIN_GROUPS) -> dict[str, str]:
    """Построить отображение «лемма → каноническая лемма».

    Args:
        groups: Группы синонимов; первое слово — каноническое.

    Returns:
        Словарь, где каждая лемма группы указывает на каноническую.

    Raises:
        ValueError: Одно слово попало в две разные группы. Тогда
            канонизация неоднозначна, и проверка начнёт подтверждать
            случайное из двух понятий.
    """
    mapping: dict[str, str] = {}
    for group in groups:
        cleaned = [word.strip().lower() for word in group if word.strip()]
        if not cleaned:
            continue
        canonical = cleaned[0]
        for word in cleaned:
            known = mapping.get(word)
            if known is not None and known != canonical:
                raise ValueError(
                    f"слово «{word}» уже входит в группу «{known}» и не может "
                    f"одновременно входить в «{canonical}»"
                )
            mapping[word] = canonical
    return mapping


def canonical(lemma: str, mapping: Mapping[str, str] | None = None) -> str:
    """Привести лемму к канонической форме понятия.

    Args:
        lemma: Лемма слова.
        mapping: Отображение групп. По умолчанию — встроенный набор.

    Returns:
        Каноническая лемма группы либо исходная лемма, если группы нет.
    """
    text = lemma.strip().lower()
    if not text:
        return ""
    table = mapping if mapping is not None else build_map()
    return table.get(text, text)
